export function createPageMetadata(pageKey, overrides = {}) {
  const page = pageSeo[pageKey]

  if (!page && !overrides.title && !overrides.description) {
    throw new Error(`Unknown SEO page key: ${pageKey}`)
  }

  const title = overrides.title ?? page?.title
  const description = overrides.description ?? page?.description
  const keywords = overrides.keywords ?? page?.keywords
  const path = overrides.path ?? page?.path ?? '/'
  const canonicalUrl = `${SITE_URL}${path}`
  const ogImage = overrides.image ?? page?.image ?? DEFAULT_OG_IMAGE

  const resolvedTitle =
    typeof title === 'object' && title.absolute
      ? title
      : typeof title === 'string'
        ? title
        : SITE_NAME

  const ogTitle =
    typeof resolvedTitle === 'object' && resolvedTitle.absolute
      ? resolvedTitle.absolute
      : typeof resolvedTitle === 'string'
        ? `${resolvedTitle} | ${SITE_NAME}`
        : SITE_NAME

  return {
    title: resolvedTitle,
    description,
    ...(keywords ? { keywords } : {}),
    alternates: {
      canonical: canonicalUrl,
    },
    openGraph: {
      title: ogTitle,
      description,
      url: canonicalUrl,
      siteName: SITE_NAME,
      type: overrides.type ?? 'website',
      locale: 'en_IN',
      ...(overrides.publishedTime
        ? { publishedTime: overrides.publishedTime }
        : {}),
      images: [
        {
          url: ogImage,
          alt: typeof resolvedTitle === 'string' ? resolvedTitle : SITE_NAME,
        },
      ],
    },
    twitter: {
      card: 'summary_large_image',
      site: TWITTER_HANDLE,
      title: ogTitle,
      description,
      images: [ogImage],
    },
  }
}

